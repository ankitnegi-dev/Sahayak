// ffmpegOnPath reports whether the real ffmpeg is installed.
func ffmpegOnPath() bool {
	_, err := exec.LookPath("ffmpeg")
	return err == nil
}

func TestFFmpeg_CheckReportsAvailability(t *testing.T) {
	err := asr.CheckFFmpeg(context.Background(), "ffmpeg")

	if !ffmpegOnPath() {
		// The binary is absent, so the tool must say so clearly rather than
		// failing with an opaque exec error later.
		if err == nil {
			t.Error("CheckFFmpeg() = nil, want an error when ffmpeg is absent")
		} else if !errors.Is(err, asr.ErrFFmpegUnavailable) {
			t.Errorf("error = %v, want ErrFFmpegUnavailable", err)
		}
		return
	}

	if err != nil {
		t.Errorf("CheckFFmpeg() error = %v, want nil", err)
	}
}

func TestFFmpeg_MissingBinaryIsReportedClearly(t *testing.T) {
	missing := filepath.Join(t.TempDir(), "no-such-ffmpeg")

	err := asr.CheckFFmpeg(context.Background(), missing)
	if err == nil {
		t.Fatal("error = nil, want an error")
	}
	if !errors.Is(err, asr.ErrFFmpegUnavailable) {
		t.Errorf("error = %v, want ErrFFmpegUnavailable", err)
	}
}

func TestFFmpeg_ConvertRejectsEmptyAudio(t *testing.T) {
	_, err := asr.NewFFmpeg().Convert(context.Background(), asr.Audio{}, asr.Linear16Mono16k)
	if !errors.Is(err, asr.ErrNoAudio) {
		t.Errorf("error = %v, want ErrNoAudio", err)
	}
}

func TestFFmpeg_ConvertMissingBinary(t *testing.T) {
	conv := &asr.FFmpeg{
		BinaryPath: filepath.Join(t.TempDir(), "no-such-ffmpeg"),
		Timeout:    2 * time.Second,
	}

	audio := asr.Audio{Data: []byte("audio"), MimeType: "audio/ogg"}
	_, err := conv.Convert(context.Background(), audio, asr.Linear16Mono16k)

	if err == nil {
		t.Fatal("error = nil, want ErrFFmpegUnavailable")
	}
	if !errors.Is(err, asr.ErrFFmpegUnavailable) {
		t.Errorf("error = %v, want ErrFFmpegUnavailable", err)
	}
}

// The source buffer must be wiped on the error path too, or a failed
// conversion leaves the audio in memory.
func TestFFmpeg_ConvertWipesSourceOnError(t *testing.T) {
	conv := &asr.FFmpeg{
		BinaryPath: filepath.Join(t.TempDir(), "no-such-ffmpeg"),
		Timeout:    2 * time.Second,
	}

	data := []byte("sensitive voice bytes")
	audio := asr.Audio{Data: data, MimeType: "audio/ogg"}

	_, _ = conv.Convert(context.Background(), audio, asr.Linear16Mono16k)

	for i, b := range data {
		if b != 0 {
			t.Fatalf("byte %d = %d after a failed conversion, want 0", i, b)
		}
	}
}

// A real conversion needs ffmpeg installed, so it is skipped when absent.
func TestFFmpeg_ConvertRealAudio(t *testing.T) {
	if !ffmpegOnPath() {
		t.Skip("ffmpeg is not installed on this machine")
	}

	source := filepath.Join(t.TempDir(), "tone.ogg")
	// One second of a 440 Hz tone, generated by ffmpeg itself so the test
	// needs no fixture file.
	gen := exec.Command("ffmpeg", "-hide_banner", "-loglevel", "error",
		"-f", "lavfi", "-i", "sine=frequency=440:duration=1", "-c:a", "libopus", "-y", source)
	if out, err := gen.CombinedOutput(); err != nil {
		t.Skipf("could not generate test audio: %v: %s", err, out)
	}

	raw, err := os.ReadFile(source)
	if err != nil {
		t.Fatalf("read generated audio: %v", err)
	}
	if len(raw) == 0 {
		t.Fatal("generated audio is empty")
	}

	audio := asr.Audio{Data: raw, MimeType: "audio/ogg", Format: "ogg"}
	converted, err := asr.NewFFmpeg().Convert(context.Background(), audio, asr.Linear16Mono16k)
	if err != nil {
		t.Fatalf("Convert() error = %v", err)
	}

	if converted.Format != "wav" {
		t.Errorf("Format = %q, want wav", converted.Format)
	}
	if converted.SampleRate != 16000 {
		t.Errorf("SampleRate = %d, want 16000", converted.SampleRate)
	}
	if converted.MimeType != "audio/wav" {
		t.Errorf("MimeType = %q, want audio/wav", converted.MimeType)
	}
	if len(converted.Data) == 0 {
		t.Error("converted audio is empty")
	}

	// WAV files start with the RIFF header, which proves real output.
	if len(converted.Data) < 4 || string(converted.Data[:4]) != "RIFF" {
		t.Errorf("output is not a RIFF/WAV file: %q", headBytes(converted.Data))
	}
}

func headBytes(b []byte) string {
	if len(b) > 8 {
		return string(b[:8])
	}
	return string(b)
}

func TestFFmpeg_ConvertHonoursTimeout(t *testing.T) {
	if !ffmpegOnPath() {
		t.Skip("ffmpeg is not installed on this machine")
	}

	conv := &asr.FFmpeg{Timeout: time.Nanosecond}

	audio := asr.Audio{Data: []byte("not really audio"), MimeType: "audio/ogg"}
	_, err := conv.Convert(context.Background(), audio, asr.Linear16Mono16k)

	if err == nil {
		t.Fatal("error = nil, want a timeout")
	}
	if !strings.Contains(err.Error(), "ffmpeg") {
		t.Errorf("error = %v, want it to mention ffmpeg", err)
	}
}
